/**
 * Тексты и раскладка оверлея. Координаты — узлы Figma в кадре-заголовке (1479×832).
 * `side` — с какой стороны плашки выходит линия к объекту, `len` — её длина.
 */
export interface Tooltip {
  title: string;
  text: string;
  x: number; y: number; w: number;
  side: 'left' | 'right' | 'top' | 'bottom';
  len: number;
  /** сдвиг появления относительно кадра-заголовка, в долях кадра */
  delay?: number;
}

export interface Location {
  id: string;
  index: number;
  num: string;
  title: string;
  /** размер заголовка в px макета */
  titleSize: number;
  titleWidth?: number;
  text: string;
  textWidth: number;
  titleFrame: number;
  theme: 'light' | 'dark';
  tooltips: Tooltip[];
  /** плашки на тёмном фоне непрозрачные */
  tooltipStyle?: 'glass' | 'solid';
  /** вертикальное смещение блока заголовка от центра */
  offsetY?: number;
  /** кадр появления заголовка и плашек (по умолчанию titleFrame − 0.45) */
  titleIn?: number;
}

