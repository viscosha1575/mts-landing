/**
 * Тексты и раскладка оверлея. Координаты — узлы Figma в кадре-заголовке (1479×832).
 * Переносы строк в заголовках, абзацах и плашках — ровно как в макете (`\n`), на десктопе строки не переносятся.
 * `side` — с какой стороны плашки выходит линия к объекту, `len` — её длина.
 */
export interface Tooltip {
  title: string;
  text: string;
  x: number; y: number; w: number;
  side: 'left' | 'right' | 'top' | 'bottom';
  len: number;
  /** ширина текстового узла, если в Figma он уже/шире внутренней ширины плашки */
  tw?: number;
  /** сдвиг появления относительно кадра-заголовка, в долях кадра */
  delay?: number;
}

export interface Location {
  id: string;
  index: number;
  num: string;
  title: string;
  /** размер заголовка в px макета */
  titleSize: number;
  titleWidth?: number;
  /** интерлиньяж заголовка в px макета (в Figma 54.42 или line-height 1) */
  titleLine?: number;
  /** типографика плашек: размер заголовка, текста и интерлиньяж текста (px макета) */
  tip: { title: number; text: number; line: number };
  text: string;
  textWidth: number;
  titleFrame: number;
  theme: 'light' | 'dark';
  tooltips: Tooltip[];
  /** плашки на тёмном фоне непрозрачные */
  tooltipStyle?: 'glass' | 'solid';
  /** вертикальное смещение блока заголовка от центра */
  offsetY?: number;
  /** кадр появления заголовка и плашек (по умолчанию titleFrame − 0.45) */
  titleIn?: number;
}

