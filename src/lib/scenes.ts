/**
 * Описание локаций.
 *
 * Координаты — в системе фрейма Figma 1479×832.
 *  - space: 'scene'  — прямоугольник задан в пространстве локации (кадр-заголовок = 1:1),
 *                      слой двигается вместе с камерой.
 *  - space: 'screen' — прямоугольник задан прямо в координатах экрана (как узел в кадре Figma),
 *                      камера на него не влияет. Так удобно вести «свободные» объекты:
 *                      аэростат, который перелетает между локациями, передние планы с DOF.
 *
 * Ключи камеры сняты с геометрии фонов в кадрах Figma: cam = (tx - bx/s, ty - by/s, 1479/s, 832/s).
 */
import type { Key, Rect } from './timeline';

export type Space = 'scene' | 'screen';

export interface LayerDef {
  id: string;
  /** ключ в image-manifest.json */
  img: string;
  space: Space;
  rect: Rect | Key<Rect>[];
  /** глубина для параллакса: 0 — фон, 1 — передний план, отрицательное — дальше фона (вид за окном) */
  depth?: number;
  /** размытие в mip-уровнях (0 — резко, 3 — сильно) */
  blur?: number | Key<number>[];
  alpha?: number | Key<number>[];
  /** поворот в градусах */
  rotate?: number;
  /** показывать только на экранах шире N px (DOF-передние планы с правого края десктопного кадра) */
  minWidth?: number;
}

export interface SceneDef {
  id: string;
  title: string;
  /** кадр-заголовок (камера 1:1) */
  titleFrame: number;
  cam: Key<Rect>[];
  alpha: Key<number>[];
  /** затемнение 0…1 (1 — чёрный) */
  dim?: Key<number>[];
  /** общее размытие сцены (mip) */
  blur?: Key<number>[];
  layers: LayerDef[];
  /** светлая или тёмная сцена — для цвета шапки и текста */
  theme: 'light' | 'dark';
}

