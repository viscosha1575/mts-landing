/**
 * Экран, вырезанный в картинке: под неё кладутся два слоя с одним и тем же четырёхугольником — тёмная
 * подложка (выключенный экран) и видео. Подложка нужна всегда: пока видео не загрузилось или уже погашено,
 * сквозь вырез не должно быть видно то, что лежит под картинкой.
 */
const screen = (id: string, video: string, rect: Rect | Key<Rect>[], quad: number[], pad: readonly [number, number], extra: Partial<LayerDef> = {}): LayerDef[] => {
  // Подложка шире выреза на pad (в долях rect): когда картинка размыта, края выреза расплываются,
  // и за чёткой кромкой подложки было бы видно то, что под картинкой.
  const cx = (quad[0] + quad[2] + quad[4] + quad[6]) / 4, cy = (quad[1] + quad[3] + quad[5] + quad[7]) / 4;
  const wide = quad.map((v, i) => v + Math.sign(v - (i % 2 ? cy : cx)) * pad[i % 2]);
  return [
    { id: `${id}-off`, img: 'paint:screen-off', paint: { type: 'solid', color: '#0a0c11' }, space: extra.space ?? 'scene', rect, quad: wide, depth: extra.depth },
    { id, img: `video:${video}`, video, space: 'scene', rect, quad, ...extra },
  ];
};

