const carAt = (r: Rect, dx: number, slope: number): Rect => {
  // точка опоры — земля под серединой машины: от неё считается и сдвиг, и перспективный масштаб
  const gx = r[0] + r[2] / 2, gy = r[1] + r[3] * 0.8;
  const dy = -dx * slope, k = (gy + dy - STREET_HORIZON) / (gy - STREET_HORIZON);
  return [gx + dx - (r[2] / 2) * k, gy + dy - r[3] * 0.8 * k, r[2] * k, r[3] * k];
};
