/**
 * Описание локаций.
 *
 * Координаты — в системе фрейма Figma 1920×1080 (секция Desktop макета, кадры 01…45). Мобильные
 * сцены 01–03 заданы в своём фрейме 393×645 (`ref`), а камеру не двигают: в мобильной раскадровке
 * каждый слой масштабируется по-своему, поэтому у слоёв экранные треки прямо по узлам кадров.
 *  - space: 'scene'  — прямоугольник задан в пространстве локации (кадр-заголовок = 1:1),
 *                      слой двигается вместе с камерой.
 *  - space: 'screen' — прямоугольник задан прямо в координатах экрана (как узел в кадре Figma),
 *                      камера на него не влияет. Так удобно вести «свободные» объекты:
 *                      аэростат, который перелетает между локациями, планы с собственным параллаксом.
 *
 * Номера кадров в ключах — номера кадров макета: F(18) — кадр «18».
 * Ключи камеры сняты с геометрии фонов в кадрах Figma: cam = (tx - bx/s, ty - by/s, 1920/s, 1080/s),
 * где (bx, by, bw) — узел фона в кадре, (tx, ty, tw) — он же в кадре-заголовке, s = bw / tw.
 * Промежуточные кадры макета не всегда согласованы между собой (объект переставлен без связи с соседними),
 * поэтому наезд задаётся опорными кадрами, а путь между ними камера проходит сама — см. sampleRect().
 */
