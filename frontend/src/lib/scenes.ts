/** Трек, привязанный к наезду камеры: значение — функция её увеличения (ширина полного кадра / ширина камеры) */
function byZoom(cam: Key<Rect>[], full: number, from: number, to: number, value: (zoom: number) => number): Key<number>[] {
  const keys: Key<number>[] = [{ f: from, v: value(1) }];
  for (let n = from + 0.05; n < to + 1e-6; n += 0.05) keys.push({ f: n, v: value(full / sampleRect(cam, frameToT(n))[2]) });
  return keys;
}
