/**
 * Камера улицы, пока камера квартиры отъезжает от окна: из полного кадра — к виду из окна.
 *
 * Вид из окна шире самой картинки улицы: у дальнего плана и у дома есть края (слева, справа и снизу),
 * и за ними только небо. Пока проём окна больше экрана, прикрыть их нечем, поэтому улица стоит в полном
 * кадре; отъезжать она начинает, когда рама вошла в кадр, и отстаёт от неё — края всё время остаются
 * за стеной. Как и город за окном офиса, вид привязан не ко времени, а к отъезду камеры квартиры.
 */
function streetBehindWindow(): Key<Rect>[] {
  const from = Math.log(APT_CAM[0].v[2]), to = Math.log(FULL[2]);
  // Доля отъезда камеры квартиры (в логарифме), с которой улица трогается. Правый откос окна входит в кадр
  // на 0.53 (квартира ×3.3) — позже левого; с 0.56 края улицы прикрыты с запасом в 80 px при любом зуме.
  const start = 0.56;
  const keys: Key<Rect>[] = [];
  let hold: Key<Rect> | null = null;
  for (let n = 41.95; n < 44.7 - 1e-6; n += 0.05) {
    const z = (Math.log(sampleRect(APT_CAM, frameToT(F(n)))[2]) - from) / (to - from);
    const u = (z - start) / (1 - start);
    // до старта улица стоит: последний такой ключ остаётся, чтобы сплайн не тронулся раньше
    if (u <= 0) { hold = { f: F(n), v: FULL }; continue; }
    if (hold) { keys.push(hold); hold = null; }
    keys.push({ f: F(n), v: lerpRect(FULL, STREET_IN_WINDOW, u * u * (3 - 2 * u)) });
  }
  return keys;
}

