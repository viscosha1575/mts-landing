/** Процедурная текстура: рисуется на канвасе при загрузке (Stage.ts), в сборку картинкой не идёт */
export type Paint =
  | { type: 'solid'; color: string }
  /** линейный градиент; точки — в долях прямоугольника слоя, base — подложка под полупрозрачными стопами */
  | { type: 'linear'; aspect: number; from: [number, number]; to: [number, number]; stops: [number, string][]; base?: string }
  /** круг, размытый по Гауссу; радиус и sigma — в долях полуширины слоя */
  | { type: 'glow'; rgb: [number, number, number]; opacity: number; radius: number; sigma: number }
  /** светильник: ядро цвета rgb (доля `core` радиуса слоя) и ореол цвета halo вокруг; кладётся в режиме add */
  | { type: 'lamp'; rgb: [number, number, number]; halo: [number, number, number]; core: number };

export interface LayerDef {
  id: string;
  /** ключ в image-manifest.json; у процедурных слоёв — просто уникальное имя текстуры */
  img: string;
  paint?: Paint;
  space: Space;
  rect: Rect | Key<Rect>[];
  /** глубина для параллакса: 0 — фон, 1 — передний план, отрицательное — дальше фона (вид за окном, облака) */
  depth?: number;
  /** размытие в px макета, как layer blur в Figma */
  blur?: number | Key<number>[];
  alpha?: number | Key<number>[];
  /** поворот в градусах */
  rotate?: number;
  /** показывать только на экранах шире N px */
  minWidth?: number;
  /**
   * режим наложения: screen — облака на дневном небе, add (plus-lighter) — свет и блик,
   * darker (plus-darker) — тень вычитается из фона, multiply — фон умножается на слой (дерево против света)
   */
  blend?: 'screen' | 'add' | 'darker' | 'multiply';
  /** не темнеет вместе со сценой: огни, которые остаются гореть в темноте */
  lit?: boolean;
  /**
   * Глубина резкости. `zone` — эллипс в том же пространстве, что и rect слоя (задан своим прямоугольником):
   * внутри него слой резкий, за ним плавно размывается сильнее на `blur` px макета. Так при наезде на предмет
   * он остаётся в фокусе, а то, что за ним, — нет.
   */
  dof?: { zone: Rect; blur: number | Key<number>[] };
  /**
   * Облако плывёт по горизонтали вместе с прокруткой: на сколько px макета оно смещается вправо за кадр
   * раскадровки. На кадре SceneDef.driftFrom стоит на месте из макета. Уйдя за край кадра, возвращается с другой стороны.
   */
  drift?: number;
  /** видео вместо картинки: имя файла в public/video (без расширения); `img` тогда — просто уникальное имя */
  video?: string;
  /** с какой секунды ролик начинает играть и с какой скоростью (один ролик на нескольких слоях идёт вразнобой) */
  videoStart?: number;
  videoRate?: number;
  /**
   * Четырёхугольник внутри прямоугольника слоя, на который натянута текстура: углы (левый верхний, правый
   * верхний, правый нижний, левый нижний) в долях rect. Так экран монитора задаётся в координатах картинки,
   * в которой он вырезан: видео-слой получает тот же rect, что и картинка, и рисуется под ней.
   */
  quad?: readonly number[];
  /**
   * Маска: слой виден только там, где она светлая (свет, который должен лечь на окна, а не на стены).
   * `img` — ключ картинки в манифесте, `in` — где она лежит в прямоугольнике слоя: x0, y0, x1, y1 в его долях.
   */
  mask?: { img: string; in: readonly [number, number, number, number] };
  /**
   * Оттенок: множители каналов rgb в степени amount — 0 без изменений, 1 — множители целиком, −1 — обратные.
   * Так один предмет в двух картинках (аэростат в небе и его модель в тёплом свете центра) меняет свет плавно,
   * а не скачком в момент, когда одна картинка сменяет другую.
   */
  tint?: { rgb: readonly [number, number, number]; amount: Key<number>[] };
  /** множитель яркости (экран в тени тусклее) */
  gain?: number;
  /** ветер: на сколько px макета ходит верхушка спрайта; низ стоит на месте */
  sway?: number;
  /** мигание огоньков: на сколько ячеек делится слой, какая их доля мигает и во сколько раз чаще обычного (rate) */
  twinkle?: { grid: readonly [number, number]; share: number; rate?: number };
  /** сдвиг от мыши берётся у соседнего слоя сцены (id): спрайт, вырезанный из него, не отъезжает от своего места */
  attach?: string;
  /**
   * Струи воздуха перед слоем (до двух): в каждой зоне (то же пространство, что и rect; середина нижней стороны —
   * источник, струя идёт вверх и расширяется) картинка слегка дрожит, как сквозь горячий воздух. `amp` — размах в px макета.
   */
  haze?: { zones: Rect[]; amp: number | Key<number>[] };
  /** пересвет 0…1: светлое уходит в белый, как у камеры, выставленной по тёмному интерьеру */
  expose?: number | Key<number>[];
  /** свет «дышит»: слой плавно проступает и уходит, период в секундах (вторая картинка той же сцены в другом свете) */
  pulse?: number;
  /**
   * дым из трубы — слой рисует шейдер, текстура не нужна: труба стоит у нижнего края на 0.16 ширины слоя слева,
   * `lean` — на сколько ширин слоя струю относит ветром вправо к верхнему краю
   */
  smoke?: { lean: number };
  /** свет дышит: на какую долю яркости он плавно притухает и снова разгорается (у каждого слоя свой ритм) */
  glimmer?: number;
  /**
   * Предмет сам ездит по кругу, по времени. `points` — маршрут: где центр предмета (px макета, в том же пространстве,
   * что rect) и на какой секунде круга он туда приходит; две одинаковые точки подряд — остановка, перед ней предмет
   * тормозит, после неё разгоняется. До первой точки и после последней он стоит в них (обе — за кадром). `period` —
   * длина круга. rect слоя задан для положения `home`; `horizon` — y линии горизонта: чем ниже в кадре, тем крупнее.
   */
  route?: { home: readonly [number, number]; points: readonly (readonly [number, number, number])[]; period: number; horizon: number };
  /** предмет в воздухе: идёт за мышью (px макета) и покачивается сам (px макета) */
  hover?: number;
  bob?: number;
  /** «дыхание» облака: на сколько px макета шум смещает выборку текстуры */
  cloud?: number;
  /**
   * Кивок при остановке. Предмет приезжает по своему треку и встаёт на кадре `at`: на последних пикселях пути
   * кузов клюёт носом — поворачивается на `deg` градусов (по часовой стрелке: нос справа) вокруг точки `pivot`
   * (доли rect: земля посередине между колёсами), качается назад и успокаивается. Качается только кузов, как
   * на подвеске: `body` — доли высоты спрайта, выше первой всё поворачивается целиком, ниже второй (колёса
   * на земле) стоит на месте. Идёт по времени, а не за прокруткой: докрутили до остановки — машина кивнула.
   * Чем медленнее она подъезжала, тем кивок слабее.
   */
  nod?: { at: number; deg: number; pivot: readonly [number, number]; body: readonly [number, number] };
}

