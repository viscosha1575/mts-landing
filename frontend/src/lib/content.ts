/**
 * Тексты и раскладка оверлея. Координаты — узлы Figma в кадре-заголовке локации (фрейм 1920×1080,
 * секция Desktop макета AGJMz0OKAVwgcjI1P4bYWG).
 * Переносы строк в заголовках, абзацах и плашках — ровно как в макете (`\n`), на десктопе строки не переносятся.
 * У каждой локации есть мобильная раскладка (`mobile`, секция 25:196 макета): заголовок сверху и по одной
 * плашке на кадр, тексты те же, строки переносятся сами. В мобильном макете у локаций 04–07 тексты — заглушка
 * (копия заголовка и плашки исследовательского центра), а кадр с плашкой один; раскладка взята из него,
 * тексты — десктопные, и на каждую плашку локации свой шаг. У квартиры в макете плашек нет.
 *
 * Тексты локаций 05–08 в макете не дописаны: часть плашек — копии соседних или lorem ipsum. Такие плашки
 * сюда не перенесены (их места в кадре перечислены у локации), а где в плашку попал текст другой локации,
 * оставлен утверждённый текст прежней версии.
 */
export interface Tooltip {
  title: string;
  text: string;
  /** левый верхний угол и ширина плашки */
  x: number; y: number; w: number;
  /** сторона плашки, из которой выходит выноска, и длина её первого отрезка (0 — плашка без выноски) */
  side: 'left' | 'right' | 'top' | 'bottom';
  len: number;
  /** точка выхода вдоль стороны, от левого/верхнего угла плашки (по умолчанию — середина стороны) */
  at?: number;
  /** излом под прямым углом: длина второго отрезка (+ вправо/вниз, − влево/вверх) */
  turn?: number;
}

/** Плашка мобильного кадра: текст берётся из tooltips[tip], выноска тянется к точке сцены */
export interface MobileTip {
  tip: number;
  /** кадр мобильной раскадровки, на котором плашка показана */
  frame: number;
  /** ширина плашки и сторона, из которой выходит выноска; `at` — точка выхода для нижней стороны */
  w: number;
  side: 'right' | 'bottom';
  at?: number;
  /** куда указывает выноска — точка в координатах мобильного фрейма 393×645 */
  target: readonly [number, number];
}

export interface MobileLayout {
  /** верх блока заголовка и верх плашки (y макета − 60) */
  titleY: number;
  tipY: number;
  titleSize: number;
  titleWidth?: number;
  textWidth: number;
  tips: MobileTip[];
  /** кадр таймлайна с заголовком, если плашек у локации нет */
  frame?: number;
  /** размытое пятно под заголовком, если на телефоне оно нужно не там, где на десктопе */
  glow?: 'dark' | 'light' | 'warm';
}

export interface Location {
  id: string;
  index: number;
  num: string;
  title: string;
  /** размер и интерлиньяж заголовка в px макета 1920 */
  titleSize: number;
  titleLine: number;
  text?: string;
  /** ширина абзаца в px макета */
  textWidth?: number;
  /** кадр-заголовок: номер кадра секции Desktop макета */
  frame: number;
  /** цвет текста: тёмный на светлой сцене или белый на тёмной */
  theme: 'light' | 'dark';
  /** размытое пятно под заголовком, как в макете: тёмное в дата-центре, светлое на пёстром городе, тёплое на закате */
  glow?: 'dark' | 'light' | 'warm';
  tooltips: Tooltip[];
  mobile?: MobileLayout;
}

