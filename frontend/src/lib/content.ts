/**
 * Тексты и раскладка оверлея. Координаты — узлы Figma в кадре-заголовке: 1920×1080 у локаций 01–03,
 * 1479×832 у локаций 04–07 (`legacy`: их плашки масштабируются множителем LEGACY_SCALE, а номера
 * кадров — номера прежнего макета, в таймлайн их переводит оверлей).
 * Переносы строк в заголовках, абзацах и плашках — ровно как в макете (`\n`), на десктопе строки не переносятся.
 * У локаций 01–03 есть мобильная раскладка (`mobile`, секция Mobile макета): заголовок сверху и по
 * одной плашке на кадр, тексты те же, строки переносятся сами.
 */
export interface Tooltip {
  title: string;
  text: string;
  /** левый верхний угол и ширина плашки */
  x: number; y: number; w: number;
  /** сторона плашки, из которой выходит выноска, и длина её первого отрезка */
  side: 'left' | 'right' | 'top' | 'bottom';
  len: number;
  /** точка выхода вдоль стороны, от левого/верхнего угла плашки (по умолчанию — середина стороны) */
  at?: number;
  /** излом под прямым углом: длина второго отрезка (+ вправо/вниз, − влево/вверх) */
  turn?: number;
  /** ширина текстового узла, если в Figma он уже/шире внутренней ширины плашки */
  tw?: number;
  /** сдвиг появления относительно кадра-заголовка, в долях кадра */
  delay?: number;
}

/** Плашка мобильного кадра: текст берётся из tooltips[tip], выноска тянется к точке сцены */
export interface MobileTip {
  tip: number;
  /** кадр мобильной раскадровки, на котором плашка показана */
  frame: number;
  /** ширина плашки и сторона, из которой выходит выноска; `at` — точка выхода для нижней стороны */
  w: number;
  side: 'right' | 'bottom';
  at?: number;
  /** куда указывает выноска — точка в координатах мобильного фрейма 393×645 */
  target: readonly [number, number];
}

export interface MobileLayout {
  /** верх блока заголовка и верх плашки (y макета − 60) */
  titleY: number;
  tipY: number;
  titleSize: number;
  titleWidth?: number;
  textWidth: number;
  tips: MobileTip[];
}

export interface Location {
  id: string;
  index: number;
  num: string;
  title: string;
  /** размер и интерлиньяж заголовка в px макета 1920 */
  titleSize: number;
  titleLine: number;
  /** типографика плашек: размер заголовка, текста, интерлиньяж текста и заголовка (px макета локации) */
  tip: { title: number; text: number; line: number; titleLine?: number };
  text: string;
  /** ширина абзаца в px макета локации */
  textWidth: number;
  titleFrame: number;
  theme: 'light' | 'dark';
  tooltips: Tooltip[];
  /** плашки на тёмном фоне непрозрачные */
  tooltipStyle?: 'glass' | 'solid';
  /** локация из прежнего макета 1479×832 */
  legacy?: boolean;
  /** сколько кадра-заголовка держится текст (по умолчанию 0.9); остаток кадра — отъезд камеры */
  hold?: number;
  mobile?: MobileLayout;
}

